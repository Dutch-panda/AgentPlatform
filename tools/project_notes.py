from __future__ import annotations

import os
import re
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any


def validate_project_id(project_id: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]*", project_id):
        raise ValueError("Project ID must contain only letters, digits, underscores, or hyphens")
    return project_id


@dataclass(frozen=True)
class ProjectContext:
    project_id: str | None
    workspace_path: Path | None = None
    profile_text: str | None = None

    @property
    def link(self) -> str:
        return f"[[projects/{self.project_id}]]" if self.project_id else ""

    @property
    def frontmatter(self) -> str:
        return f'project: "{self.link}"\n' if self.project_id else ""

    @property
    def body(self) -> str:
        return f"Project: {self.link}\n\n" if self.project_id else ""

    @property
    def prompt(self) -> str:
        if not self.project_id:
            return "Project ID: none. This task has no parent project.\n"
        base = (
            f"Project ID: {self.project_id}\nParent project: {self.link}\n"
            "Keep this project ID unchanged.\n"
        )
        if self.profile_text:
            return (
                f"{base}\n"
                f"--- EXISTING PROJECT PROFILE & MEMORY ---\n"
                f"{self.profile_text}\n"
                "--- END PROJECT PROFILE ---\n"
                "Respect existing data schemas and project decisions unless explicitly requested to change.\n"
            )
        return base


def init_project_workspace(
    project_id: str,
    workspace_root: Path | str = "workspace",
) -> tuple[Path, Path]:
    """
    Ensure the project workspace exists with .gitignore, PROJECT_PROFILE.md, and local .env.
    Returns (workspace_dir, profile_path).
    """
    validate_project_id(project_id)
    root = Path(workspace_root).resolve()
    ws_dir = root / project_id
    ws_dir.mkdir(parents=True, exist_ok=True)

    # 1. Project .gitignore protecting local secrets
    gitignore_path = ws_dir / ".gitignore"
    if not gitignore_path.exists():
        gitignore_content = (
            "# Project local secrets & dependencies\n"
            ".env\n"
            ".env.*\n"
            "node_modules/\n"
            "__pycache__/\n"
            ".venv/\n"
            "*.pyc\n"
        )
        gitignore_path.write_text(gitignore_content, encoding="utf-8")

    # 2. Local .env file for secrets/IDs (mode 0600)
    env_path = ws_dir / ".env"
    if not env_path.exists():
        env_path.write_text(
            f"# Local configuration and secrets for project: {project_id}\n"
            f"# Generated by BuildRelay on {datetime.now():%Y-%m-%d}\n",
            encoding="utf-8",
        )
        try:
            os.chmod(env_path, 0o600)
        except OSError:
            pass

    # 3. Persistent living PROJECT_PROFILE.md
    profile_path = ws_dir / "PROJECT_PROFILE.md"
    if not profile_path.exists():
        initial_profile = f"""# Project Profile: {project_id}

## Overview & Objective
Project initialized: {datetime.now():%Y-%m-%d}

## Active Data Schemas & Entities
*(Populated during design and implementation)*

## User Input Surfaces & Entry Points
*(Defined during architecture alignment)*

## Confirmed Architectural Rules
*(Recorded from Grill-Me alignment interviews)*

## Task History
"""
        profile_path.write_text(initial_profile, encoding="utf-8")

    return ws_dir, profile_path


def load_project_profile(
    project_id: str,
    workspace_root: Path | str = "workspace",
) -> str | None:
    """Load the existing PROJECT_PROFILE.md content if available."""
    ws_dir = Path(workspace_root).resolve() / project_id
    profile_path = ws_dir / "PROJECT_PROFILE.md"
    if profile_path.is_file():
        return profile_path.read_text(encoding="utf-8").strip()
    return None


def get_project_env(
    project_id: str,
    workspace_root: Path | str = "workspace",
) -> dict[str, str]:
    """Parse key-value pairs from project workspace .env."""
    ws_dir = Path(workspace_root).resolve() / project_id
    env_path = ws_dir / ".env"
    if not env_path.is_file():
        return {}

    env_vars: dict[str, str] = {}
    for line in env_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" in line:
            key, val = line.split("=", 1)
            env_vars[key.strip()] = val.strip().strip("'\"")
    return env_vars


def set_project_env(
    project_id: str,
    key: str,
    value: str,
    workspace_root: Path | str = "workspace",
) -> None:
    """Safely append or update a key in project workspace .env with 0600 permissions."""
    ws_dir = Path(workspace_root).resolve() / project_id
    ws_dir.mkdir(parents=True, exist_ok=True)
    env_path = ws_dir / ".env"

    existing_lines: list[str] = []
    found = False
    if env_path.is_file():
        existing_lines = env_path.read_text(encoding="utf-8").splitlines()

    new_lines: list[str] = []
    for line in existing_lines:
        if line.strip().startswith(f"{key}=") or line.strip().startswith(f"{key} ="):
            new_lines.append(f"{key}={value}")
            found = True
        else:
            new_lines.append(line)

    if not found:
        new_lines.append(f"{key}={value}")

    env_path.write_text("\n".join(new_lines) + "\n", encoding="utf-8")
    try:
        os.chmod(env_path, 0o600)
    except OSError:
        pass


def update_project_profile(
    project_id: str,
    task_id: str,
    brief: Any = None,
    spec: Any = None,
    result: Any = None,
    workspace_root: Path | str = "workspace",
) -> Path:
    """Update PROJECT_PROFILE.md with newly completed task, schemas, and input specs."""
    validate_project_id(project_id)
    ws_dir, profile_path = init_project_workspace(project_id, workspace_root=workspace_root)
    content = profile_path.read_text(encoding="utf-8")

    # 1. Update User Input Surface if present in spec
    input_spec = getattr(spec, "input_interface_spec", None)
    if input_spec and "## User Input Surfaces & Entry Points" in content:
        section_pattern = r"(## User Input Surfaces & Entry Points\n)(.*?)(?=\n## |\Z)"
        updated_section = f"\\1{input_spec}\n"
        content = re.sub(section_pattern, updated_section, content, flags=re.S)

    # 2. Update Overview if title/objective given
    title = getattr(brief, "title", None)
    obj = getattr(brief, "objective", None)
    if title and "*(Populated during" in content:
        content = content.replace("*(Populated during design and implementation)*", f"Goal: {title}\nScope: {obj}")

    # 3. Append to Task History
    today = f"{datetime.now():%Y-%m-%d}"
    summary = getattr(result, "summary", title or "Task completed")
    history_entry = f"- **[{today}] {task_id}:** {summary}\n"

    if "## Task History" in content:
        content = content.rstrip() + "\n" + history_entry
    else:
        content += f"\n## Task History\n{history_entry}"

    profile_path.write_text(content, encoding="utf-8")
    return profile_path


def prepare_project(
    vault_path: Path,
    project_id: str | None,
    workspace_root: Path | str = "workspace",
) -> ProjectContext:
    if project_id is None:
        return ProjectContext(None)
    validate_project_id(project_id)
    vault_root = vault_path.resolve()
    projects_dir = (vault_root / "projects").resolve()
    note_path = projects_dir / f"{project_id}.md"
    if not projects_dir.is_relative_to(vault_root) or projects_dir == vault_root:
        raise ValueError("Project notes must be within the vault")
    if note_path.is_symlink():
        raise ValueError("Project notes must not be symbolic links")
    projects_dir.mkdir(parents=True, exist_ok=True)
    try:
        with note_path.open("x", encoding="utf-8") as note:
            note.write(
                f'---\nid: "{project_id}"\ntype: "project"\n'
                f'created_at: "{datetime.now():%Y-%m-%d}"\n---\n'
                f"# {project_id}\n"
            )
    except FileExistsError:
        if not note_path.is_file():
            raise ValueError("Project note path must be a Markdown file") from None

    # Initialize workspace memory and profile
    ws_dir, _ = init_project_workspace(project_id, workspace_root=workspace_root)
    profile_text = load_project_profile(project_id, workspace_root=workspace_root)
    return ProjectContext(project_id, workspace_path=ws_dir, profile_text=profile_text)
